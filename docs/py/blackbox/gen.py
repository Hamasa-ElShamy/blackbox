"""Turn an analysis into a small standalone Python reader (standard library only)."""
from .core import STRUCT


def fmt_of(r):
    lay, parts, cur = r["layout"], [], 0
    for f in r["fields"]:
        if f["kind"] in ("constant", "text"):
            parts.append(f"{f['size']}s")
        else:
            parts.append((f.get("endian", "<") if False else "") + STRUCT[f["kind"]])
    return parts


def reader_source(r, src_name):
    lay, fields = r["layout"], r["fields"]
    lines = []
    fmt_parts, names, conv = [], [], []
    for f in fields:
        if f["kind"] == "constant": continue
    # one struct per field so mixed byte order is possible
    rows = []
    for f in fields:
        if f["kind"] == "constant": rows.append((f["off"], f["size"], None, f["name"], "skip"))
        elif f["kind"] == "text": rows.append((f["off"], f["size"], f"{f['size']}s", f["name"], "text"))
        else: rows.append((f["off"], f["size"], f.get("endian", "<") + STRUCT[f["kind"]], f["name"], f["kind"]))
    out = f'''#!/usr/bin/env python3
"""Reader for {src_name}, generated by BlackBox. These field types are GUESSES.
Header: {lay['header_size']} bytes. Record: {lay['record_size']} bytes. Records: {lay['records']}.
Confidence from BlackBox: {r.get('confidence')}. Check a few rows against the real thing before you trust it.
"""
import csv, struct, sys

HEADER = {lay['header_size']}
RECORD = {lay['record_size']}
# (offset, struct format or None to skip, column name, kind)
FIELDS = [
'''
    for off, size, fmt, name, kind in rows:
        out += f"    ({off}, {fmt!r}, {name!r}, {kind!r}),\n"
    out += ']\n'
    out += '''
def read(path):
    data = open(path, "rb").read()
    n = (len(data) - HEADER) // RECORD
    if (len(data) - HEADER) % RECORD:
        print("warning: file size is not header + whole records", file=sys.stderr)
    for i in range(n):
        base = HEADER + i * RECORD
        row = {}
        for off, fmt, name, kind in FIELDS:
            if fmt is None: continue
            v = struct.unpack_from(fmt, data, base + off)[0]
            if kind == "text": v = v.split(b"\\0")[0].decode("latin-1")
            row[name] = v
        yield row


if __name__ == "__main__":
    rows = read(sys.argv[1])
    first = next(rows, None)
    if first is None: sys.exit("no records")
    w = csv.DictWriter(sys.stdout, fieldnames=list(first))
    w.writeheader(); w.writerow(first); w.writerows(rows)
'''
    return out
